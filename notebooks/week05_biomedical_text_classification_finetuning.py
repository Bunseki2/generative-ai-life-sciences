@app.cell
def _():
    # Main exercise. All variables are intentionally kept in this cell's scope.
    import numpy as np
    from datasets import Dataset
    from transformers import (
        AutoTokenizer, AutoModelForSequenceClassification,
        TrainingArguments, Trainer
    )
    from sklearn.model_selection import train_test_split
    from sklearn.metrics import accuracy_score, precision_recall_fscore_support

    # Tiny illustrative examples only. Replace with a larger, documented, licensed dataset
    # before reporting performance or presenting this as a portfolio model.
    texts = [
        "The compound inhibited CYP3A4 activity in the assay.",
        "The protein sequence contains a conserved catalytic motif.",
        "The molecule showed no measurable inhibition under tested conditions.",
        "The model predicts a likely protein-ligand interaction.",
        "The enzyme metabolizes a broad range of substrates.",
        "The peptide formed fibrils after incubation.",
        "The assay measured direct enzyme inhibition.",
        "The predicted docking score suggests a possible binding pose.",
        "The protein contains a transmembrane helix.",
        "The inhibitor reduced enzyme activity in vitro.",
        "A sequence embedding was generated by a language model.",
        "The compound showed concentration-dependent inhibition.",
    ]
    labels = [1, 0, 1, 0, 0, 0, 1, 0, 0, 1, 0, 1]  # 1=assay inhibition statement, illustrative

    train_text, val_text, train_y, val_y = train_test_split(
        texts, labels, test_size=0.33, random_state=42, stratify=labels
    )
    model_id = "distilbert/distilbert-base-uncased"
    tokenizer = AutoTokenizer.from_pretrained(model_id)
    train_ds = Dataset.from_dict({"text": train_text, "labels": train_y})
    val_ds = Dataset.from_dict({"text": val_text, "labels": val_y})

    def tokenize(batch):
        return tokenizer(batch["text"], truncation=True, padding="max_length", max_length=96)

    train_ds = train_ds.map(tokenize, batched=True)
    val_ds = val_ds.map(tokenize, batched=True)
    train_ds = train_ds.remove_columns(["text"])
    val_ds = val_ds.remove_columns(["text"])
    train_ds.set_format("torch")
    val_ds.set_format("torch")

    model = AutoModelForSequenceClassification.from_pretrained(model_id, num_labels=2)

    def compute_metrics(eval_pred):
        logits, labels_true = eval_pred
        predictions = np.argmax(logits, axis=-1)
        precision, recall, f1, _ = precision_recall_fscore_support(
            labels_true, predictions, average="binary", zero_division=0
        )
        return {
            "accuracy": accuracy_score(labels_true, predictions),
            "precision": precision,
            "recall": recall,
            "f1": f1,
        }

    args = TrainingArguments(
        output_dir="week05_classifier_output",
        learning_rate=2e-5,
        per_device_train_batch_size=4,
        per_device_eval_batch_size=4,
        num_train_epochs=2,
        weight_decay=0.01,
        eval_strategy="epoch",
        save_strategy="no",
        report_to="none",
    )
    trainer = Trainer(
        model=model, args=args, train_dataset=train_ds,
        eval_dataset=val_ds, compute_metrics=compute_metrics
    )
    # TODO: On Molab, run trainer.train() after confirming the runtime has enough memory.
    # Then run trainer.evaluate() and inspect false positives/false negatives.
    print("Ready to fine-tune:", len(train_ds), "train /", len(val_ds), "validation examples")
    print("IMPORTANT: this toy dataset is not suitable for scientific conclusions.")
    return


